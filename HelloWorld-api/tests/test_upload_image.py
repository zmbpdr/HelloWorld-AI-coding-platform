def _make_png_bytes() -> bytes:
    """生成最小的有效 PNG 文件（1x1 像素，红色）"""
    # PNG signature + IHDR + IDAT + IEND
    ihdr_data = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    ihdr_crc = struct.pack(">I", 0xe9df6845 & 0xFFFFFFFF)  # precomputed for IHDR
    # Minimal IDAT chunk (deflated 1x1 red pixel)
    idat_data = bytes.fromhex("789c6260000000100001")  # minimal zlib stream
    idat_crc = struct.pack(">I", 0xe5e8a3d9 & 0xFFFFFFFF)  # precomputed
    # IEND chunk
    iend_crc = struct.pack(">I", 0xae426082 & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += struct.pack(">I", 13) + b"IHDR" + ihdr_data + ihdr_crc
    png += struct.pack(">I", len(idat_data)) + b"IDAT" + idat_data + idat_crc
    png += struct.pack(">I", 0) + b"IEND" + iend_crc
    return png


def _make_gif_bytes() -> bytes:
    """生成最小的有效 GIF 文件（1x1 像素，透明）"""
    return (
        b"GIF89a"
        b"\x01\x00\x01\x00\x80\x00\x00"  # width=1, height=1
        b"\xff\xff\xff\x00\x00\x00"       # bg color
        b"\x21\xf9\x04\x00\x00\x00\x00\x00"  # graphic control extension
        b"\x2c\x00\x00\x00\x00\x01\x00\x01\x00\x00"  # image descriptor
        b"\x02\x02\x44\x01\x00"           # image data
        b"\x3b"                            # trailer
    )


