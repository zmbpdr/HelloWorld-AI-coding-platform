def _make_svg_bytes() -> bytes:
    """生成 SVG 文件内容"""
    return b'<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg"><circle cx="50" cy="50" r="40"/></svg>'


def _make_svg_disguised_as_jpg() -> bytes:
    """生成伪装成 .jpg 的 SVG 文件（扩展名欺骗攻击）"""
    return _make_svg_bytes()


def _make_oversized_bytes() -> bytes:
    """生成超大文件（超过 5MB 限制）"""
    return b"\x00" * (settings.MAX_UPLOAD_SIZE + 1)


def _make_unknown_bytes() -> bytes:
    """生成无法识别的文件内容"""
    return b"this is not an image file at all"


